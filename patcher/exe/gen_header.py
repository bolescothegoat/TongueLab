"""
Dev tool: turns patch_table.json into patch_data.h (the table compiled into the .exe).
usage: gen_header.py <patch_table.json> <patch_data.h>
"""
import json
import sys


def carr(b):
    return "{" + ",".join(str(x) for x in b) + "}"


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    table = json.load(open(sys.argv[1], encoding="utf-8"))
    assert table["format"] == 2
    out = ["// generated by gen_header.py from patch_table.json - do not edit", "#pragma once", "#include <cstdint>", ""]
    out.append("struct PRun { std::uint32_t offset; std::uint8_t len; const std::uint8_t* orig; const std::uint8_t* patched; };")
    out.append("struct PVariant { const char* label; std::uint32_t size; std::uint8_t src[32]; std::uint8_t dst[32]; const PRun* runs; int nruns; };")
    out.append("struct PTongue { const char* name; const PVariant* variants; int nvariants; };")
    out.append("")
    tongues = []
    for ti, (name, info) in enumerate(table["files"].items()):
        vnames = []
        for vi, v in enumerate(info["variants"]):
            runs = []
            for ri, r in enumerate(v["patches"]):
                o = bytes.fromhex(r["original"])
                p = bytes.fromhex(r["patched"])
                assert len(o) == len(p) and len(o) < 256
                out.append(f"static const std::uint8_t O_{ti}_{vi}_{ri}[] = {carr(o)};")
                out.append(f"static const std::uint8_t P_{ti}_{vi}_{ri}[] = {carr(p)};")
                runs.append(f"{{{r['offset']},{len(o)},O_{ti}_{vi}_{ri},P_{ti}_{vi}_{ri}}}")
            out.append(f"static const PRun RUNS_{ti}_{vi}[] = {{{','.join(runs)}}};")
            vnames.append(f'{{"{esc(v["label"])}",{v["size"]},{carr(bytes.fromhex(v["source_sha256"]))},{carr(bytes.fromhex(v["patched_sha256"]))},RUNS_{ti}_{vi},{len(runs)}}}')
        out.append(f"static const PVariant VARS_{ti}[] = {{{','.join(vnames)}}};")
        tongues.append(f'{{"{esc(name)}",VARS_{ti},{len(info["variants"])}}}')
        out.append("")
    out.append(f"static const PTongue TONGUES[] = {{{','.join(tongues)}}};")
    out.append(f"static const int TONGUE_COUNT = {len(tongues)};")
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", sys.argv[2], "-", len(tongues), "tongues")


if __name__ == "__main__":
    main()
